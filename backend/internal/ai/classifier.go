// Пакет ai — ИИ-классификатор заказов (rule-based)
// Определяет категорию и приоритет по ключевым словам в описании
package ai

import "strings"

// ClassifyOrder — классификация заказа по тексту описания
// Возвращает: категорию (с эмодзи) и приоритет (1=срочно, 2=средний, 3=плановый)
func ClassifyOrder(text string) (category string, priority int) {
	lower := strings.ToLower(text)

	// === ОПРЕДЕЛЕНИЕ ПРИОРИТЕТА ===
	// Приоритет 1 (срочно): ключевые слова аварии и ЧП
	urgentKeywords := []string{
		"срочно", "авария", "затопило", "прорвало", "пожар", "замыкает",
		"беда", "горит", "дым", "искрит", "бьёт током",
	}
	priority = 3 // По умолчанию — плановый
	for _, keyword := range urgentKeywords {
		if strings.Contains(lower, keyword) {
			priority = 1
			break
		}
	}

	// === ОПРЕДЕЛЕНИЕ КАТЕГОРИИ ===
	// Словари ключевых слов для каждой категории
	categories := map[string][]string{
		"Сантехника 🔧": {
			"кран", "труб", "вода", "слив", "унитаз", "сантехник",
			"затоп", "капает", "батарея", "радиатор", "смыв",
		},
		"Электрика ⚡": {
			"электрик", "розетк", "провод", "свет", "лампочк",
			"замыкает", "ток", "выбило", "автомат", "щиток",
		},
		"Уборка 🧹": {
			"убор", "пылесос", "мыть", "чист", "гряз",
			"помыть", "пол", "окна", "пыль", "мусор",
		},
		"Доставка 📦": {
			"достав", "привез", "купить", "продукт", "аптек",
			"магазин", "лекарств", "лекарства", "хлеб", "молоко",
		},
		"Ремонт 🔨": {
			"ремонт", "мебел", "дверь", "окно", "повесить",
			"сломал", "починить", "сборка", "полка", "шкаф",
		},
		"Сопровождение 🚶": {
			"сопровожд", "помоч", "дойти", "поликлиник", "больниц",
			"прогулк", "проводить", "встретить", "отвезти",
		},
	}

	category = "Прочее 📋" // По умолчанию
	for cat, keywords := range categories {
		for _, keyword := range keywords {
			if strings.Contains(lower, keyword) {
				category = cat
				break
			}
		}
		if category != "Прочее 📋" {
			break
		}
	}

	return category, priority
}
